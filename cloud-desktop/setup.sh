#!/bin/bash
# 云电脑一键配置：中文环境 + 主题美化 + 浏览器 + 应用商店 + 桌面图标
set +e
export DEBIAN_FRONTEND=noninteractive
export DISPLAY=:1
export DBUS_SESSION_BUS_ADDRESS=unix:path=/tmp/dbus-sock
export LANG=zh_CN.UTF-8 LC_ALL=zh_CN.UTF-8 LANGUAGE=zh_CN:zh
LOG=/tmp/setup.log
exec > "$LOG" 2>&1

echo "### 1/6 中文与主题包（逐个安装，失败不影响其他）"
sudo apt-get update -qq
install_pkg() {
  sudo apt-get install -y -qq --no-install-recommends "$1" >/dev/null 2>&1 \
    && echo "  OK   $1" || echo "  FAIL $1"
}
for p in locales language-pack-zh-hans \
         fonts-wqy-zenhei fonts-wqy-microhei fonts-noto-cjk fonts-noto-color-emoji \
         zenity imagemagick falkon dbus-x11 xdg-utils \
         greybird-gtk-theme papirus-icon-theme xfce4-l10n thunar-l10n; do
  install_pkg "$p"
done
sudo locale-gen zh_CN.UTF-8 2>&1 | tail -2

echo "### 2/6 Firefox 中文版"
sudo rm -rf /opt/firefox
timeout 280 curl -sL "https://download.mozilla.org/?product=firefox-latest&os=linux64&lang=zh-CN" -o /tmp/ff.tar.xz
[ -s /tmp/ff.tar.xz ] && sudo tar xJf /tmp/ff.tar.xz -C /opt/ 2>&1 | tail -1
[ -x /opt/firefox/firefox ] && echo "FIREFOX=ok" || echo "FIREFOX=none"

echo "### 3/6 Google Chrome"
timeout 280 curl -sL -o /tmp/chrome.deb https://dl.google.com/linux/direct/google-chrome-stable_current_amd64.deb
if [ -s /tmp/chrome.deb ]; then
  sudo apt-get install -y -qq /tmp/chrome.deb 2>&1 | tail -2
  sudo apt-get -f install -y -qq 2>&1 | tail -1
fi
command -v google-chrome-stable >/dev/null && echo "CHROME=ok" || echo "CHROME=none"
command -v falkon >/dev/null && echo "FALKON=ok" || echo "FALKON=none"

echo "### 4/6 壁纸"
mkdir -p "$HOME/.local/share/backgrounds"
WP="$HOME/.local/share/backgrounds/cloud-desktop.jpg"
if command -v convert >/dev/null 2>&1; then
  convert -size 1600x1000 gradient:'#101a2b'-'#2b5876' \
    -font "WenQuanYi-Micro-Hei" -pointsize 72 -fill '#ffffffff' \
    -gravity center -annotate +0-50 '云 电 脑' \
    -pointsize 26 -fill '#ffffffaa' -annotate +0+70 'Cloud Desktop' \
    "$WP" 2>&1 | tail -1
  [ -s "$WP" ] || convert -size 1600x1000 gradient:'#101a2b'-'#2b5876' "$WP" 2>&1 | tail -1
fi
if [ ! -s "$WP" ]; then
  python3 - <<'PYEOF'
import zlib, struct
W, H = 1600, 1000
rows = b""
for y in range(H):
    t = y / (H - 1)
    r = int(0x10 + (0x2b - 0x10) * t)
    g = int(0x1a + (0x58 - 0x1a) * t)
    b = int(0x2b + (0x76 - 0x2b) * t)
    rows += b"\x00" + bytes([r, g, b]) * W
def chunk(tag, data):
    c = struct.pack(">I", len(data)) + tag + data
    return c + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)
png = b"\x89PNG\r\n\x1a\n"
png += chunk(b"IHDR", struct.pack(">IIBBBBB", W, H, 8, 2, 0, 0, 0))
png += chunk(b"IDAT", zlib.compress(rows, 9))
png += chunk(b"IEND", b"")
open("$WP", "wb").write(png)
print("wallpaper generated by python")
PYEOF
fi
ls -l "$WP" 2>/dev/null
echo "WALLPAPER=$(ls -l "$WP" 2>/dev/null | wc -l)"

echo "### 5/6 主题与字体"
THEME=Greybird-dark
[ -d /usr/share/themes/Greybird-dark ] || THEME=Greybird
[ -d /usr/share/themes/$THEME ] || THEME=Adwaita-dark
ICON=Papirus
[ -d /usr/share/icons/Papirus ] || ICON=Adwaita
xfconf-query -c xsettings -p /Net/ThemeName -s "$THEME" --create -t string 2>/dev/null
xfconf-query -c xsettings -p /Net/IconThemeName -s "$ICON" --create -t string 2>/dev/null
xfconf-query -c xsettings -p /Gtk/FontName -s "Noto Sans CJK SC 11" --create -t string 2>/dev/null
xfconf-query -c xsettings -p /Gtk/MonospaceFontName -s "Noto Sans Mono CJK SC 11" --create -t string 2>/dev/null
xfconf-query -c xsettings -p /Xft/Hinting -s 1 --create -t int 2>/dev/null
xfconf-query -c xsettings -p /Xft/HintStyle -s hintslight --create -t string 2>/dev/null
xfconf-query -c xsettings -p /Xft/Antialias -s 1 --create -t int 2>/dev/null
xfconf-query -c xsettings -p /Xft/RGBA -s rgb --create -t string 2>/dev/null
xfconf-query -c xfwm4 -p /general/theme -s "$THEME" --create -t string 2>/dev/null
xfconf-query -c xfwm4 -p /general/use_compositing -s false --create -t bool 2>/dev/null
for p in /backdrop/screen0/monitor0/image-path /backdrop/screen0/monitorVirtual-1/image-path /backdrop/screen0/monitorVNC-0/image-path /backdrop/screen0/monitoreDP-1/image-path; do
  xfconf-query -c xfce4-desktop -p "$p" -s /usr/share/backgrounds/xfce/cloud-desktop.jpg --create -t string 2>/dev/null
  xfconf-query -c xfce4-desktop -p "${p/image-path/image-style}" -s 3 --create -t int 2>/dev/null
done
xfconf-query -c xfce4-desktop -p /desktop-icons/style -s 2 --create -t int 2>/dev/null
echo "THEME=$THEME ICON=$ICON"

echo "### 6/6 应用商店与图标"
sudo install -m 755 "$(dirname "$0")/app-store.sh" /usr/local/bin/app-store.sh
sudo rm -f /usr/local/bin/应用商店
sudo ln -sf /usr/local/bin/app-store.sh /usr/local/bin/应用商店 2>/dev/null
ls -l /usr/local/bin/app-store.sh

mkdir -p "$HOME/Desktop"
FF=""; [ -x /opt/firefox/firefox ] && FF=/opt/firefox/firefox
CH=""; command -v google-chrome-stable >/dev/null && CH=/usr/bin/google-chrome-stable
FK=""; command -v falkon >/dev/null && FK=/usr/bin/falkon
mk() { printf '[Desktop Entry]\nVersion=1.0\nType=Application\nName=%s\nName[zh_CN]=%s\nComment=%s\nExec=%s\nIcon=%s\nTerminal=%s\nCategories=%s;\n' "$2" "$2" "$2" "$3" "$4" "$5" "$6" > "$HOME/Desktop/$1"; }
[ -n "$FF" ] && mk firefox.desktop "Firefox 火狐" "$FF" firefox false Network
[ -n "$CH" ] && mk chrome.desktop "谷歌浏览器" "$CH --no-sandbox" google-chrome false Network
[ -n "$FK" ] && mk falkon.desktop "Falkon 浏览器" "$FK" falkon false Network
mk appstore.desktop "应用商店" "/usr/local/bin/app-store.sh" system-software-install true System
mk terminal.desktop "终端" "xfce4-terminal" utilities-terminal false System
mk files.desktop "文件管理器" "thunar" org.xfce.thunar false System
chmod 755 "$HOME/Desktop"/*.desktop 2>/dev/null
gio set "$HOME/Desktop"/*.desktop metadata::xfce-exe-checksum "*" 2>/dev/null
ls "$HOME/Desktop"

echo "### 自启 Firefox"
[ -n "$FF" ] && { export MOZ_DISABLE_CONTENT_SANDBOX=1; setsid nohup "$FF" --display=:1 about:blank > /tmp/ff-run.log 2>&1 < /dev/null & sleep 8; }

echo "### 诊断"
echo "zenity: $(command -v zenity || echo MISSING)"
echo "appstore: $(wc -c < /usr/local/bin/app-store.sh) bytes"
echo "### zenity 冒烟测试"
timeout 15 zenity --info --text="测试" --title="商店自检" >/dev/null 2>&1
echo "zenity_gui_rc=$?"
pkill -f "zenity" 2>/dev/null
echo "SETUP_DONE"
